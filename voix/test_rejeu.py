"""Qui a parlé, quand on rouvre une conversation.

Ce que ce fichier protège : **une ligne attribuée à toi dans la page doit être une ligne que
tu as dite.** Rien d'autre.

Le bug qui l'a motivé, vu sur un téléphone le 13 octobre 2026 : en rouvrant la conversation
`insnap`, la page affichait sous « TOI », à l'horodatage de la reprise, un bloc de quinze
lignes commençant par `<task-notification>` — l'avis de fin d'une tâche de fond, inséré par
le CLI. Mathieu ne l'avait jamais écrit, et la page jurait le contraire.

La cause tient en une phrase : dans un transcript Claude Code, le rôle « user » ne veut pas
dire « l'utilisateur a parlé », il veut dire « ce n'est pas le modèle ». Le CLI s'en sert
aussi pour ses propres injections. Mesure du jour sur les 1 982 messages « user » à contenu
texte de cette machine : 124 ne venaient pas de lui.

    ../.venv/bin/python voix/test_rejeu.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import journal

ok = True


def dire(bon: bool, texte: str):
    global ok
    ok = ok and bon
    print(f"  {'OK  ' if bon else 'ECHEC'} {texte}")


# Le bloc exact du bug, recopié de la capture — pas une reconstitution.
NOTIFICATION = (
    "<task-notification>\n"
    "<task-id>wpk2i24il</task-id>\n"
    "<tool-use-id>toolu_01DFiwKjBa9NnKCUMTXJAeqA</tool-use-id>\n"
    "<output-file>/tmp/claude-1000/tasks/wpk2i24il.output</output-file>\n"
    "<status>completed</status>\n"
    "<summary>Dynamic workflow \"Veille terrain + mesures reelles\" completed</summary>\n"
    "<result>{\"veilles\":[{\"cle\":\"snapchat-detection\"}]}</result>\n"
    "</task-notification>"
)

COMPACTION = ("This session is being continued from a previous conversation that ran out of "
              "context. The summary below covers the earlier portion.")


class FauxMessage:
    """Ce que rend `get_session_messages` : un objet dont `.message` est la charge brute."""

    def __init__(self, charge):
        self.message = charge


def utilisateur(texte):
    return FauxMessage({"role": "user", "content": texte})


def assistant(*blocs):
    return FauxMessage({"role": "assistant", "content": list(blocs)})


def rejouer(messages):
    """Branche le faux transcript à la place du SDK et rend les événements rejoués."""
    import claude_agent_sdk
    vrai = getattr(claude_agent_sdk, "get_session_messages", None)
    claude_agent_sdk.get_session_messages = lambda sid, directory=None: messages
    try:
        evenements, _ = journal.rejouer_session("sess-test")
    finally:
        if vrai is not None:
            claude_agent_sdk.get_session_messages = vrai
    return evenements


def genres(evenements):
    return [e["genre"] for e in evenements]


def principal():
    # ---------------------------------------------------------------------------------
    # TU — reconnaître ce qui ne vient pas de l'utilisateur
    # ---------------------------------------------------------------------------------
    print("\nTU — reconnaitre un message insere par la machine")

    dire(journal.message_injecte(NOTIFICATION),
         "l'avis de fin de tache de fond n'est pas de toi")
    dire(journal.message_injecte(COMPACTION),
         "le resume de compaction n'est pas de toi")
    for balise in ("<system-reminder>rappel</system-reminder>",
                   "<local-command-stdout>Set model to `x`</local-command-stdout>",
                   "<command-name>/model</command-name>",
                   "<command-message>model</command-message>",
                   "<local-command-caveat>Caveat: …</local-command-caveat>",
                   "Caveat: The messages below were generated by the user while running"):
        dire(journal.message_injecte(balise),
             f"ni « {balise[:28]}… »")

    dire(journal.message_injecte("\n  " + NOTIFICATION),
         "un bloc precede d'un saut de ligne est reconnu quand meme")

    # L'autre moitie du contrat, et la plus importante : ne RIEN confisquer de ce qui vient
    # vraiment de lui. Un message qui parle de ces blocs reste un message a lui.
    for vrai in ("Continue",
                 "regarde la notification <task-notification> qui s'affiche sous mon nom",
                 "This session is fine",
                 "<p>du html colle dans la barre</p>",
                 "caveat emptor"):
        dire(not journal.message_injecte(vrai),
             f"« {vrai[:38]}… » reste de toi")

    print("\nTU — la ligne lisible qui remplace le bloc brut")

    libelle = journal.libelle_injecte(NOTIFICATION)
    dire("tâche de fond terminée" in libelle,
         "l'avis de fin dit qu'une tache de fond est terminee")
    dire("Veille terrain" in libelle,
         "et dit LAQUELLE : le resume de la tache survit, c'est tout son interet")
    dire("<task-notification>" not in libelle and "toolu_" not in libelle,
         "sans une ligne de balises ni d'identifiant d'outil")

    dire(journal.libelle_injecte(NOTIFICATION.replace("completed", "failed")).startswith(
         "tâche de fond échouée"), "une tache qui echoue le dit")
    dire(journal.libelle_injecte("<task-notification><task-id>abc</task-id>"
                                 "</task-notification>").endswith("abc"),
         "sans resume, l'identifiant de la tache tient lieu de nom")
    dire(journal.libelle_injecte("<task-notification></task-notification>")
         == "tâche de fond terminée",
         "et sans rien du tout, la ligne reste une phrase, pas un tiret orphelin")

    dire("compactée" in journal.libelle_injecte(COMPACTION),
         "le resume de compaction se lit comme un compactage")
    dire(journal.libelle_injecte("<command-name>/model</command-name>")
         == "commande locale : /model",
         "une commande locale est nommee")
    dire(journal.libelle_injecte("<local-command-stdout>ok</local-command-stdout>")
         == "sortie d'une commande locale", "et sa sortie aussi")
    dire(journal.libelle_injecte("<system-reminder>x</system-reminder>")
         == "rappel système inséré dans le fil", "un rappel systeme se nomme")

    # Un bloc tronque par la limite de rejeu ne doit pas faire tomber la relecture.
    dire(journal.libelle_injecte("<task-notification><summary>coupe au milieu")
         .startswith("tâche de fond terminée — coupe au milieu"),
         "une balise jamais refermee ne fait pas tomber la relecture")

    long = "<task-notification><summary>" + "a" * 400 + "</summary></task-notification>"
    dire(len(journal.libelle_injecte(long)) < 260,
         "un resume de 400 caracteres est coupe : une ligne de flux reste une ligne")

    # ---------------------------------------------------------------------------------
    # TI — la relecture d'une session branchee sur le transcript
    # ---------------------------------------------------------------------------------
    print("\nTI — ce que la relecture d'une session publie")

    evenements = rejouer([
        utilisateur("relance la veille"),
        assistant({"type": "tool_use", "id": "t1", "name": "Bash",
                   "input": {"command": "./veille.sh", "description": "Détail du risque"}}),
        utilisateur([{"type": "tool_result", "tool_use_id": "t1", "content": "lancé"}]),
        utilisateur(NOTIFICATION),
        assistant({"type": "text", "text": "La veille a abouti."}),
    ])

    toi = [e for e in evenements if e["genre"] == "toi"]
    dire(len(toi) == 1, "un seul message m'est attribue : celui que j'ai vraiment envoye")
    dire(toi[0]["texte"] == "relance la veille", "et c'est bien celui-la")

    machine = [e for e in evenements if e["genre"] == "systeme"]
    dire(len(machine) == 1, "l'avis de fin de tache est publie, pas jete")
    dire("tâche de fond terminée" in machine[0]["texte"],
         "sous un genre qui dit d'ou il vient")
    dire("<task-notification>" not in str(evenements),
         "aucune balise brute ne survit dans le flux")

    dire("outil" in genres(evenements) and "resultat" in genres(evenements),
         "le reste de la relecture est intact : l'outil et son resultat sont la")
    dire("texte" in genres(evenements), "la reponse ecrite aussi")

    # Un transcript qui n'est QUE des injections ne doit produire aucune ligne « toi ».
    muet = rejouer([utilisateur(NOTIFICATION), utilisateur(COMPACTION),
                    utilisateur("<local-command-stdout>ok</local-command-stdout>")])
    dire(not [e for e in muet if e["genre"] == "toi"],
         "une session faite d'injections ne me fait rien signer du tout")
    dire(len(muet) == 3, "les trois restent visibles, sous leur vrai genre")

    # ---------------------------------------------------------------------------------
    # TF — le parcours tel qu'il se vit
    # ---------------------------------------------------------------------------------
    print("\nTF — je rouvre la conversation sur mon telephone")

    # Le scenario exact de la capture : une tache de fond lancee, un tour qui se termine,
    # la notification qui tombe pendant que la page etait fermee, puis la reprise.
    page = rejouer([
        utilisateur("lance la veille terrain en arriere-plan"),
        assistant({"type": "tool_use", "id": "t9", "name": "Bash",
                   "input": {"command": "veille", "run_in_background": True,
                             "description": "Détail du risque Snapchat"}}),
        utilisateur([{"type": "tool_result", "tool_use_id": "t9",
                      "content": "Running in background (ID: wpk2i24il)"}]),
        utilisateur(NOTIFICATION),
        assistant({"type": "text", "text": "Verdict : faisable avec réserves."}),
        utilisateur("ok, resume-moi ca"),
    ])

    signes = [e["texte"] for e in page if e["genre"] == "toi"]
    dire(signes == ["lance la veille terrain en arriere-plan", "ok, resume-moi ca"],
         "en relisant la page, je ne retrouve que mes deux phrases")
    dire(not any(t.startswith("<") for t in signes),
         "et aucune ne commence par un chevron — c'etait le symptome visible")

    ligne = [e for e in page if e["genre"] == "systeme"]
    dire(len(ligne) == 1 and "Veille terrain" in ligne[0]["texte"],
         "la fin de la tache lancee il y a vingt minutes reste lisible : c'est pour elle "
         "qu'on rouvre la page")

    # Et le filtre de la page doit connaitre ce genre. Un genre absent de la legende cree
    # une ligne invisible qu'aucune case ne peut rallumer — c'est deja arrive avec
    # « session », et c'est le genre de panne qu'on ne voit jamais.
    legende = (os.path.join(os.path.dirname(os.path.abspath(__file__)), "tableau.py"))
    with open(legende, encoding="utf-8") as f:
        source = f.read()
    dire('g: "systeme"' in source,
         "le genre « machine » figure dans la legende du tableau, donc il est filtrable")

    print(f"\n{'TOUT VERT' if ok else 'DES ECHECS'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(principal())
